def run(config: StackConfig) -> dict[str, dict[str, Any]]:
    if not 1 <= config.top_k <= 30:
        raise ValueError("top_k must be between 1 and 30")
    if config.cost_bps < 0.0:
        raise ValueError("cost_bps must be non-negative")
    if config.min_train_months < 6:
        raise ValueError("min_train_months must be at least six")
    if config.ridge_alpha <= 0.0 or config.lightgbm_rounds < 1:
        raise ValueError("ridge_alpha must be positive and lightgbm_rounds must be positive")

    prices, volumes, tickers = research.load_prices(config.price_field)
    prices = prices.loc[prices.index <= config.end]
    volumes = volumes.reindex(prices.index)
    features = research.make_features(prices, volumes)
    panels = load_forecast_panels(config.foundation_forecasts, config.deep_forecasts, tickers)
    panel, base_ensemble, _ = build_stack_panel(panels, features, config.start, config.end)

    errors: dict[str, str] = {}
    ridge_raw, ridge_raw_training = walk_forward_stacker(
        panel, "ridge", "target", config.min_train_months, config.ridge_alpha, config.lightgbm_rounds
    )
    ridge_excess, ridge_excess_training = walk_forward_stacker(
        panel, "ridge", "target_excess", config.min_train_months, config.ridge_alpha, config.lightgbm_rounds
    )
    try:
        lightgbm_raw, lightgbm_raw_training = walk_forward_stacker(
            panel, "lightgbm", "target", config.min_train_months, config.ridge_alpha, config.lightgbm_rounds
        )
        lightgbm_excess, lightgbm_excess_training = walk_forward_stacker(
            panel, "lightgbm", "target_excess", config.min_train_months, config.ridge_alpha, config.lightgbm_rounds
        )
    except RuntimeError as exc:
        errors["lightgbm"] = str(exc)
        empty = pd.DataFrame(index=panel["signal_date"].drop_duplicates().sort_values(), columns=sorted(panel["ticker"].unique()), dtype=float)
        lightgbm_raw = empty.copy()
        lightgbm_excess = empty.copy()
        lightgbm_raw_training = pd.Series(index=empty.index, dtype=float)
        lightgbm_excess_training = pd.Series(index=empty.index, dtype=float)

    prediction_panels: dict[str, pd.DataFrame] = {
        "existing_composite": panels["existing_composite"].reindex(index=panel["signal_date"].drop_duplicates().sort_values()),
        "forecast_rank_ensemble": base_ensemble,
        "stack_ridge_raw": ridge_raw,
        "stack_ridge_excess": ridge_excess,
    }
    if not lightgbm_raw.notna().any().any():
        errors.setdefault("stack_lightgbm_raw", errors.get("lightgbm", "no LightGBM forecasts"))
        errors.setdefault("stack_lightgbm_excess", errors.get("lightgbm", "no LightGBM forecasts"))
    else:
        prediction_panels["stack_lightgbm_raw"] = lightgbm_raw
        prediction_panels["stack_lightgbm_excess"] = lightgbm_excess
    prediction_panels["stack_ridge_lgbm_50"] = rank_blend(ridge_raw, lightgbm_raw)
    prediction_panels["stack_base_ridge_50"] = rank_blend(base_ensemble, ridge_raw)

    primary_stack_names = (
        "stack_ridge_raw",
        "stack_ridge_excess",
        "stack_lightgbm_raw",
        "stack_lightgbm_excess",
    )
    active_starts = [
        start
        for name in primary_stack_names
        if name in prediction_panels and (start := _active_start(prediction_panels[name])) is not None
    ]
    evaluation_start = min(active_starts) if active_starts else pd.Timestamp(config.start)
    evaluation_features = _slice_features(features, str(evaluation_start.date()), config.end)
    prediction_panels = {
        name: predictions.loc[predictions.index >= evaluation_start]
        for name, predictions in prediction_panels.items()
    }
    simulations: dict[str, pd.DataFrame] = {}
    metrics: dict[str, dict[str, dict[str, Any]]] = {}
    for name, predictions in prediction_panels.items():
        simulation = ml_research.simulate_predictions(
            predictions,
            evaluation_features,
            config.top_k,
            config.cost_bps,
        )
        simulations[name] = simulation
        metrics[name] = _metrics(simulation, config)

    training_rows = pd.DataFrame(
        [
            {
                "model": model,
                "target": target,
                "signals": int(predictions.notna().any(axis=1).sum()),
                "forecast_rows": int(predictions.notna().sum().sum()),
                "median_training_rows": float(training.dropna().median()) if not training.dropna().empty else np.nan,
            }
            for model, target, predictions, training in (
                ("stack_ridge_raw", "target", ridge_raw, ridge_raw_training),
                ("stack_ridge_excess", "target_excess", ridge_excess, ridge_excess_training),
                ("stack_lightgbm_raw", "target", lightgbm_raw, lightgbm_raw_training),
                ("stack_lightgbm_excess", "target_excess", lightgbm_excess, lightgbm_excess_training),
            )
        ]
    )
    write_report(
        config,
        panels,
        prediction_panels,
        simulations,
        metrics,
        training_rows,
        errors,
        evaluation_features,
    )
    return metrics


