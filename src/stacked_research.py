"""Leakage-safe stacking of factor and foundation-model forecasts.

This module tests a small second-stage cross-sectional forecaster inspired by
the asset-pricing machine-learning literature.  The first-stage forecasts are
generated by :mod:`src.foundation_research` and :mod:`src.deep_ml_research`.
At every month-end, their cross-sectional ranks become inputs to a regularized
Ridge model or a shallow LightGBM model.  The stacker is refit with an
expanding window using only signal dates strictly before the forecast date.

The raw forecast files are intentionally ignored by Git because they can be
large and depend on model weights.  Run the foundation and deep experiments
before this module.  This is an audit harness, not a live trading strategy or
a claim that pretrained models have an Indonesian equity edge.
"""

