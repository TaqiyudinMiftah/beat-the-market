def _json_safe(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]
    if isinstance(value, np.generic):
        return _json_safe(value.item())
    if isinstance(value, float) and not np.isfinite(value):
        return None
    return value


def _safe_nanmean(values: np.ndarray, axis: int) -> np.ndarray:
    """Return NaN for all-missing slices without noisy runtime warnings."""
    valid = np.isfinite(values)
    count = valid.sum(axis=axis)
    total = np.nansum(values, axis=axis)
    result = np.full(count.shape, np.nan, dtype=float)
    np.divide(total, count, out=result, where=count > 0)
    return result


def _read_forecast_file(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"Missing {path}. Run the foundation/deep research runners before stacking."
        )
    frame = pd.read_csv(path)
    required = {"model", "signal_date", "ticker", "forecast"}
    missing = sorted(required - set(frame.columns))
    if missing:
        raise ValueError(f"{path} is missing columns: {', '.join(missing)}")
    frame["signal_date"] = pd.to_datetime(frame["signal_date"])
    frame["forecast"] = pd.to_numeric(frame["forecast"], errors="coerce")
    if frame.duplicated(["model", "signal_date", "ticker"]).any():
        raise ValueError(f"{path} contains duplicate model/date/ticker forecasts")
    return frame


def _model_panels(frame: pd.DataFrame, models: tuple[str, ...]) -> dict[str, pd.DataFrame]:
    panels: dict[str, pd.DataFrame] = {}
    for model in models:
        subset = frame.loc[frame["model"].eq(model)]
        if subset.empty:
            raise ValueError(f"Forecast file does not contain required model {model!r}")
        panels[model] = (
            subset.pivot(index="signal_date", columns="ticker", values="forecast")
            .sort_index()
            .sort_index(axis=1)
            .astype(float)
        )
    return panels


def load_forecast_panels(
    foundation_path: Path,
    deep_path: Path,
    tickers: list[str],
) -> dict[str, pd.DataFrame]:
    """Load and align primitive forecast panels from the two prior runs."""
    foundation = _model_panels(_read_forecast_file(foundation_path), BASE_MODELS[:4])
    deep = _model_panels(_read_forecast_file(deep_path), BASE_MODELS[4:])
    panels = {**foundation, **deep}
    common_dates = pd.DatetimeIndex(
        sorted(set.intersection(*(set(panel.index) for panel in panels.values())))
    )
    common_tickers = sorted(
        set(tickers).intersection(
            set.intersection(*(set(panel.columns) for panel in panels.values()))
        )
    )
    if common_dates.empty or not common_tickers:
        raise ValueError("No common dates and tickers exist across the forecast files")
    aligned = {
        model: panel.reindex(index=common_dates, columns=common_tickers)
        for model, panel in panels.items()
    }
    # Missing symbol-month forecasts are retained.  Learned stackers use
    # complete rows only; rank ensembles can still use the available models.
    # This is preferable to imputing a model's prediction or silently
    # shrinking the universe differently for each experiment.
    return aligned


def build_stack_panel(
    panels: dict[str, pd.DataFrame],
    features: dict[str, pd.DataFrame | pd.Series],
    start: str,
    end: str,
) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, pd.DataFrame]]:
    """Build rank features and next-month targets for the stacker."""
    if tuple(panels) != BASE_MODELS:
        panels = {model: panels[model] for model in BASE_MODELS}
    rank_panels = {
        model: panel.rank(axis=1, pct=True, method="average")
        for model, panel in panels.items()
    }
    common_dates = pd.DatetimeIndex(
        sorted(set.intersection(*(set(panel.index) for panel in rank_panels.values())))
    )
    common_dates = common_dates[(common_dates >= pd.Timestamp(start)) & (common_dates <= pd.Timestamp(end))]
    tickers = sorted(set.intersection(*(set(panel.columns) for panel in rank_panels.values())))
    monthly_returns = features["monthly_returns"]
    benchmark_returns = features["benchmark_returns"]
    assert isinstance(monthly_returns, pd.DataFrame)
    assert isinstance(benchmark_returns, pd.Series)
    target = monthly_returns.shift(-1)
    benchmark_next = benchmark_returns.shift(-1)
    common_dates = common_dates.intersection(target.index)
    if common_dates.empty or not tickers:
        raise ValueError("No aligned signal dates with next-month targets")

    rank_values = np.stack(
        [rank_panels[model].reindex(index=common_dates, columns=tickers).to_numpy() for model in BASE_MODELS],
        axis=2,
    )
    rank_mean = _safe_nanmean(rank_values, axis=2)
    centered = rank_values - rank_mean[:, :, None]
    rank_dispersion = np.sqrt(_safe_nanmean(centered * centered, axis=2))
    rows: list[pd.DataFrame] = []
    for date_position, signal_date in enumerate(common_dates):
        frame = pd.DataFrame({"ticker": tickers})
        for model_position, model in enumerate(BASE_MODELS):
            frame[f"{model}_rank"] = rank_values[date_position, :, model_position]
        frame["rank_mean"] = rank_mean[date_position]
        frame["rank_dispersion"] = rank_dispersion[date_position]
        frame["target"] = target.reindex(index=[signal_date], columns=tickers).iloc[0].to_numpy()
        benchmark_value = benchmark_next.get(signal_date, np.nan)
        frame["target_excess"] = frame["target"] - benchmark_value
        frame["signal_date"] = signal_date
        rows.append(frame)
    panel = pd.concat(rows, ignore_index=True)
    panel["signal_date"] = pd.to_datetime(panel["signal_date"])
    base_ensemble = pd.DataFrame(
        rank_mean,
        index=common_dates,
        columns=tickers,
    )
    return panel, base_ensemble, rank_panels


def _training_and_current(
    panel: pd.DataFrame,
    signal_date: pd.Timestamp,
    target_column: str,
    min_train_months: int,
) -> tuple[pd.DataFrame, pd.DataFrame] | None:
    required = [*STACK_FEATURE_NAMES, target_column]
    train = panel.loc[panel["signal_date"] < signal_date].dropna(subset=required)
    current = panel.loc[panel["signal_date"].eq(signal_date)].dropna(subset=STACK_FEATURE_NAMES)
    if train["signal_date"].nunique() < min_train_months or current.empty:
        return None
    return train, current


def _winsorize(values: np.ndarray) -> np.ndarray:
    return ml_research._winsorize(values)


def _ridge_fit_predict(
    train: pd.DataFrame,
    current: pd.DataFrame,
    target_column: str,
    alpha: float,
) -> pd.Series:
    x_train = train.loc[:, STACK_FEATURE_NAMES].to_numpy(dtype=float)
    y_train = _winsorize(train[target_column].to_numpy(dtype=float))
    x_current = current.loc[:, STACK_FEATURE_NAMES].to_numpy(dtype=float)
    mean = x_train.mean(axis=0)
    scale = x_train.std(axis=0)
    scale[scale < 1e-9] = 1.0
    z_train = (x_train - mean) / scale
    z_current = (x_current - mean) / scale
    system = z_train.T @ z_train + alpha * np.eye(z_train.shape[1])
    coefficients = np.linalg.solve(system, z_train.T @ (y_train - y_train.mean()))
    prediction = y_train.mean() + z_current @ coefficients
    return pd.Series(prediction, index=current["ticker"].to_numpy())


def _lightgbm_fit_predict(
    train: pd.DataFrame,
    current: pd.DataFrame,
    target_column: str,
    rounds: int,
) -> pd.Series:
    try:
        import lightgbm as lgb
    except ImportError as exc:  # pragma: no cover - optional environment
        raise RuntimeError("LightGBM is not installed; install requirements-ml.txt") from exc
    x_train = train.loc[:, STACK_FEATURE_NAMES].to_numpy(dtype=float)
    x_current = current.loc[:, STACK_FEATURE_NAMES].to_numpy(dtype=float)
    dataset = lgb.Dataset(
        x_train,
        label=_winsorize(train[target_column].to_numpy(dtype=float)),
        feature_name=list(STACK_FEATURE_NAMES),
        free_raw_data=True,
    )
    model = lgb.train(
        {
            "objective": "regression",
            "learning_rate": 0.03,
            "num_leaves": 7,
            "max_depth": 3,
            "min_data_in_leaf": 30,
            "lambda_l1": 1.0,
            "lambda_l2": 20.0,
            "feature_fraction": 0.8,
            "bagging_fraction": 0.8,
            "bagging_freq": 1,
            "seed": 42,
            "feature_fraction_seed": 42,
            "bagging_seed": 42,
            "data_random_seed": 42,
            "deterministic": True,
            "force_col_wise": True,
            "verbosity": -1,
        },
        dataset,
        num_boost_round=rounds,
    )
    return pd.Series(model.predict(x_current), index=current["ticker"].to_numpy())


def walk_forward_stacker(
    panel: pd.DataFrame,
    model: str,
    target_column: str,
    min_train_months: int = DEFAULT_MIN_TRAIN_MONTHS,
    ridge_alpha: float = DEFAULT_RIDGE_ALPHA,
    lightgbm_rounds: int = DEFAULT_LIGHTGBM_ROUNDS,
) -> tuple[pd.DataFrame, pd.Series]:
    """Fit a stacker at each date using only earlier signal months."""
    if model not in {"ridge", "lightgbm"}:
        raise ValueError(f"Unsupported stacker model: {model}")
    tickers = sorted(panel["ticker"].dropna().unique())
    signal_dates = pd.DatetimeIndex(sorted(panel["signal_date"].unique()))
    predictions = pd.DataFrame(index=signal_dates, columns=tickers, dtype=float)
    training_counts = pd.Series(index=signal_dates, dtype=float)
    for signal_date in signal_dates:
        prepared = _training_and_current(panel, pd.Timestamp(signal_date), target_column, min_train_months)
        if prepared is None:
            continue
        train, current = prepared
        if model == "ridge":
            predicted = _ridge_fit_predict(train, current, target_column, ridge_alpha)
        else:
            predicted = _lightgbm_fit_predict(train, current, target_column, lightgbm_rounds)
        predictions.loc[signal_date, predicted.index] = predicted.to_numpy()
        training_counts.loc[signal_date] = len(train)
    return predictions, training_counts


def rank_blend(*predictions: pd.DataFrame) -> pd.DataFrame:
    """Average available cross-sectional ranks without filling missing models."""
    if not predictions:
        raise ValueError("At least one prediction panel is required")
    index = predictions[0].index
    columns = predictions[0].columns
    ranked = [ml_research.rank_predictions(panel.reindex(index=index, columns=columns)) for panel in predictions]
    values = np.stack([panel.to_numpy(dtype=float) for panel in ranked], axis=2)
    blended = _safe_nanmean(values, axis=2)
    all_missing = np.all(~np.isfinite(values), axis=2)
    blended[all_missing] = np.nan
    return pd.DataFrame(blended, index=index, columns=columns)


def _slice_features(
    features: dict[str, pd.DataFrame | pd.Series],
    start: str,
    end: str,
) -> dict[str, pd.DataFrame | pd.Series]:
    result: dict[str, pd.DataFrame | pd.Series] = {}
    start_date = pd.Timestamp(start)
    end_date = pd.Timestamp(end)
    for name, value in features.items():
        if isinstance(value.index, pd.DatetimeIndex):
            result[name] = value.loc[(value.index >= start_date) & (value.index <= end_date)]
        else:  # pragma: no cover - current research inputs are date-indexed
            result[name] = value
    return result


